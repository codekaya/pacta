const WHATSAPP_NUMBER = (process.env.NEXT_PUBLIC_PACTA_WHATSAPP ?? '').replace(/\D/g, '');

export function whatsappHref(locale: Locale): string | null {
  if (!WHATSAPP_NUMBER) return null;
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(copy[locale].whatsapp.message)}`;
}

