export type Locale = 'en' | 'tr';

export type SitePath = string;

export function href(locale: Locale, path: SitePath = '', hash = ''): string {
  const base = locale === 'en' ? path || '/' : `/tr${path}`;
  return `${base}${hash}`;
}

